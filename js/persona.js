/** 组装本轮发给模型的 system 内容 */
export function buildSystem(mode, memory) {
  const parts = [SYSTEM_PROMPT, MODE_RULES[mode] ?? MODE_RULES.daily]

  if (memory?.facts?.length) {
    parts.push(
      `【你记得关于 TA 的事】\n${memory.facts
        .slice(-8)
        .map((f) => `- ${f}`)
        .join('\n')}\n在合适的时候可以自然地提起，不要生硬复述。`,
    )
  }

  if (memory?.topics?.length) {
    parts.push(`【最近聊过】${memory.topics.slice(-5).join('、')}`)
  }

  return parts.join('\n\n')
}
