/**
 * 【危险表述检测】—— 独立于模型的安全兜底层
 *
 * 设计原则：这一层不依赖 LLM 的判断，也不依赖提示词被正确执行。
 * 只要命中，就直接走人设文档规定的"危机干预三步法"硬编码回复，
 * 不给模型任何"忘记照做"的机会。
 *
 * ⚠️ 维护须知：这里的词表是保守设计，宁可多触发也不能漏。
 *    多触发只会让一次普通对话变得温柔一点，漏触发可能造成真实伤害。
 */

/** 一级：直接的危险意图与即时危险 */
const CRITICAL = [
  /自杀/, /轻生/, /想死/, /不想活/, /活不下去/, /没法活了/,
  /结束(自己的)?(生命|一生)/, /了结(自己|此生)/, /一了百了/,
  /割腕/, /跳楼/, /跳河/, /跳下去/, /上吊/, /自缢/, /吞药/, /烧炭/,
  /安眠药.*(吃|吞|喝)/,
  /(准备|打算|想要|决定).{0,6}(死|去死)/,
  /遗书/, /告别(世界|大家)/,
  /(已经|正在).{0,4}(割|划).{0,3}(手腕|胳膊)/,
  /自残/, /自伤/, /伤害自己/, /惩罚自己/,
]

/** 二级：强烈的心理痛苦与绝望（不一定有明确意图，但需要进入安抚模式） */
const DISTRESS = [
  /抑郁/, /绝望/, /崩溃/, /撑不住/, /受不了了/, /扛不住/,
  /好难受/, /很难受/, /喘不过气/, /心好痛/, /好痛苦/,
  /焦虑/, /恐慌/, /好害怕/, /失眠/, /睡不着.*(痛苦|难受)/,
  /没有意义/, /没意思/, /毫无意义/, /活着.*(累|没意思|痛苦)/,
  /被(孤立|抛弃|讨厌)/, /没人(在乎|爱我|理解)/, /一个人.*(好累|好难受)/,
  /压力好大/, /喘不过来/,
]

/** 三级：轻度低落 —— 只用于提示，不强制切换重模式 */
const LOW = [
  /难过/, /伤心/, /委屈/, /想哭/, /哭了/, /不开心/, /烦躁/,
  /好累/, /疲惫/, /emo/, /低落/, /郁闷/, /烦死/,
]

/** 否定语境：避免"我不会自杀"这类表述被误判为一级 */
const NEGATED = [
  /(不|没|别|無|无)会?(想)?(自杀|轻生|去死)/,
  /(不|没)想(死|自杀)/,
  /不会(伤害自己|自残)/,
  /(拒绝|反对|劝).{0,6}(自杀|轻生)/,
]

/**
 * 判断一段用户输入的危险等级。
 * @param {string} text 用户输入
 * @returns {{level:'critical'|'distress'|'low'|'none', hit:string|null}}
 */
export function detectRisk(text) {
  const t = String(text ?? '')
  if (!t.trim()) return { level: 'none', hit: null }

  const negated = NEGATED.some((re) => re.test(t))

  // 一级：直接危险。否定语境下需要更谨慎地确认——
  // 但"我没有想死"也可能是掩饰，所以只对明确的否定句式降级，不整体放过。
  for (const re of CRITICAL) {
    if (re.test(t)) {
      if (negated) return { level: 'distress', hit: `negated:${re.source}` }
      return { level: 'critical', hit: re.source }
    }
  }

  for (const re of DISTRESS) {
    if (re.test(t)) return { level: 'distress', hit: re.source }
  }

  for (const re of LOW) {
    if (re.test(t)) return { level: 'low', hit: re.source }
  }

  return { level: 'none', hit: null }
}

